/**
 * The Worker's bindings and variables. `[vars]` come from the wrangler tomls (and `.dev.vars`
 * locally); the secrets are set by Launch (`launch.kit.json` → `launchProvides`). Everything is
 * read through `loadConfig` (config.ts), never straight off `env` in a route.
 */
export interface Env {
  ASSETS: Fetcher
  RATE_LIMIT_KV: KVNamespace
  APP_ENV?: string
  APP_URL?: string
  APP_NAME?: string
  RELEASE_VERSION?: string
  /** `neon` (deployed) or `postgres` (local Docker, the default when unset). */
  DATABASE_DRIVER?: string
  DATABASE_URL?: string
  /** Local only: route the neon driver through a Neon proxy in front of a local Postgres. */
  NEON_LOCAL_PROXY?: string
  /** 64 hex chars, generated by Launch once per environment: signs the session cookies. */
  SESSION_SECRET?: string
  OIDC_ISSUER?: string
  OIDC_CLIENT_ID?: string
  OIDC_CLIENT_SECRET?: string
  /** `true`: OIDC is the only way in (no development sign-in, even locally). */
  AUTH_OIDC_ONLY?: string
  /** Comma-separated emails that are admins (`/api/me` → `admin: true`). */
  BOOTSTRAP_ADMIN_EMAILS?: string
}
